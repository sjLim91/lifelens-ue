import assert from 'node:assert/strict';
import * as THREE from 'three';
import { source } from './compile.mjs';
const { VegetationLayer } = await source('render/vegetation-layer.ts');
const { GroundDetailLayer } = await source('render/ground-detail-layer.ts');
const { NaturalResourceProjection } = await source('render/natural-resource-projection.ts');
const { snowPresentationCoverage } = await source('render/environment-surface-presentation.ts');
const { createTerrainElevationSampler, createTerrainGeometryBuilder } = await source('render/terrain-geometry.ts');
const { WaterLayer } = await source('render/water-layer.ts');
const { WorldSession } = await source('runtime/world-session.ts');
const { ResidentContinuity } = await source('runtime/resident-continuity.ts');
const starts = [];
const session = new WorldSession({ createWorld: (...args) => starts.push(args),
  createEarthWorld: (...args) => { starts.push(args); return true; } }, new ResidentContinuity());
session.createWorld('v4'); assert(session.createEarthWorld('v4', 37, 126));
assert.deepEqual(starts, [['v4', '', 4], ['v4', 37, 126, 4]]);
const w = { available: true, worldSeed: 'lifecycle', centerChunkX: 0, centerChunkY: 0,
  chunks: [{ x: 0, y: 0, elevation01: .25, waterKind: 'None', waterAvailability: .5,
    forestCoverage01: 1, grassCoverage01: 1, shrubCoverage01: 1, rockCoverage01: 0 }] };
const trees = Array.from({ length: 8 }, (_, ordinal) => ({ id: `wood:${ordinal}`, ordinal,
  ageDays: 10950, remainingWood: 10, capacity: 10, felledMinute: -1, generation: 0 }));
const resource = { id: 'wood', material: 'Wood', gridX: 16, gridY: 16, quantity: 80, maxQuantity: 80, trees };
const projection = r => new NaturalResourceProjection({ available: true, resources: [r] }, w);
const forest = new VegetationLayer(); forest.setTerrain(w, projection(resource));
const before = forest.instanceCount; assert(before > 0); assert.equal(forest.stumps.count, 0);
const felled = { ...resource, quantity: 0, trees: trees.map(t => ({ ...t, remainingWood: 0, felledMinute: 50 })) };
forest.setTerrain(w, projection(felled)); assert(forest.instanceCount < before); assert(forest.stumps.count > 0);
const reloaded = new VegetationLayer(); reloaded.setTerrain(w, projection(felled));
assert.deepEqual(forest.stumps.instanceMatrix.array, reloaded.stumps.instanceMatrix.array);
forest.setTerrain(w, projection({ ...resource, trees: trees.map(t => ({ ...t, ageDays: 4, felledMinute: 50, generation: 1 })) }));
assert(forest.instanceCount > 0); assert(forest.stumps.count > 0);
assert(forest.instanceMatrices[5] < reloaded.stumps.instanceMatrix.array[5] * 10);
const vegetation = new GroundDetailLayer();
const food = { id: 'food', material: 'PlantFood', gridX: 16, gridY: 16, quantity: 80, maxQuantity: 80, flower01: 1, fruit01: 1 };
vegetation.setTerrain(w, projection(food)); assert(vegetation.flowers.count > 0 && vegetation.fruits.count > 0);
vegetation.setTerrain(w, projection({ ...food, flower01: 0, fruit01: 0 }));
assert.equal(vegetation.flowers.count, 0); assert.equal(vegetation.fruits.count, 0);
vegetation.setTerrain(w, projection({ ...food, quantity: 0 })); assert.equal(vegetation.fruits.count, 0);
assert(snowPresentationCoverage({ available: true, snowDepthMeters: .12, precipitationType: 'None', airTemperatureC: -3 }) > .9);
assert.equal(snowPresentationCoverage({ available: true, snowDepthMeters: 0, precipitationType: 'Snow', precipitationIntensity01: 1, airTemperatureC: -3 }), 0);
const samples = Array.from({ length: 289 }, (_, i) => .25 + (i % 17) * .001 + Math.floor(i / 17) * .002);
const detailed = { ...w, chunks: [{ ...w.chunks[0], elevationSamples: samples }] };
const sampler = createTerrainElevationSampler(detailed);
assert(Math.abs(sampler(0, 0, .5, .5) - samples[8 * 17 + 8]) < 1e-10);
const geometry = createTerrainGeometryBuilder(detailed) (detailed.chunks[0]);
assert.equal(geometry.getAttribute('position').count, 289);
assert([...geometry.getAttribute('position').array, ...geometry.getAttribute('normal').array].every(Number.isFinite));
const water = new WaterLayer(); assert.equal(water.openWaterMaterial.ior, 1.333);
assert(water.reflectionTarget.width <= 128);
water.setTerrain({ ...w, chunks: [{ ...w.chunks[0], waterKind: 'Lake' }] });
water.openWaterMesh.geometry.dispose(); water.openWaterMesh.geometry = new THREE.PlaneGeometry(2, 2);
const originalTarget = {}; let restored;
water.reflectionCamera.update = () => { throw new Error('capture failure'); };
const renderer = { xr: { enabled: true }, getRenderTarget: () => originalTarget, setRenderTarget: t => restored = t };
assert.throws(() => water.updateReflection(renderer, new THREE.Scene(), new THREE.PerspectiveCamera()), /capture failure/);
assert(water.group.visible && renderer.xr.enabled); assert.equal(restored, originalTarget);
forest.dispose(); reloaded.dispose(); vegetation.dispose(); geometry.dispose(); water.dispose();
console.log('PASS Core tree → stump → coppice, reload identity, flowers/fruit, persisted snow, detailed grounding, bounded reflection/failure cleanup');
