import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(import.meta.dirname, '../..');

function read(relativePath) {
  return fs.readFileSync(path.join(repoRoot, relativePath), 'utf8');
}

function parseLiteralInt(source, name, sourcePath) {
  const pattern = new RegExp(
    String.raw`(?:inline\s+)?constexpr\s+int\s+${name}\s*=\s*(-?\d+)\s*;`,
  );
  const match = source.match(pattern);
  if (!match) {
    throw new Error(
      `Unable to resolve ${name} from Core source: ${sourcePath}`,
    );
  }
  return Number.parseInt(match[1], 10);
}

const worldGenesisPath =
  'Source/LifeLensCore/include/lifelens/WorldGenesis.h';
const simulationCalendarPath =
  'Source/LifeLensCore/include/lifelens/SimulationCalendar.h';

const worldGenesis = read(worldGenesisPath);
const simulationCalendar = read(simulationCalendarPath);

const worldChunkSpanGridCells = parseLiteralInt(
  worldGenesis,
  'WorldChunkSpanGridCells',
  worldGenesisPath,
);
const simulationMinutesPerHour = parseLiteralInt(
  simulationCalendar,
  'SimulationMinutesPerHour',
  simulationCalendarPath,
);
const simulationHoursPerDay = parseLiteralInt(
  simulationCalendar,
  'SimulationHoursPerDay',
  simulationCalendarPath,
);
const simulationMinutesPerDay =
  simulationMinutesPerHour * simulationHoursPerDay;

// Goal observations carry persisted MaterialKind ordinals. Derive the names
// from the same Core enum instead of maintaining a second Web enum.
const materialBlock = read('Source/LifeLensCore/include/lifelens/Civilization.h')
  .match(/enum class MaterialKind\s*\{([\s\S]*?)\};/);
if (!materialBlock) throw new Error('Core MaterialKind enum is missing');
let nextMaterial = 0;
const materialNames = {};
for (const entry of materialBlock[1].replace(/\/\/[^\n]*/g, '').split(',')) {
  if (!entry.trim()) continue;
  const match = entry.trim().match(/^(\w+)(?:\s*=\s*(\d+))?$/);
  if (!match) throw new Error('Unsupported Core MaterialKind declaration');
  if (match[2] !== undefined) nextMaterial = Number(match[2]);
  materialNames[nextMaterial++] = match[1];
}

const outputPath = path.join(
  repoRoot,
  'web/src/runtime/generated-core-contract.ts',
);

const output = `// AUTO-GENERATED by web/scripts/generate-core-contract.mjs.
// Core headers are the source of truth. Do not edit this file manually.

export const CORE_WORLD_CHUNK_SPAN_GRID_CELLS =
  ${worldChunkSpanGridCells} as const;

export const CORE_SIMULATION_MINUTES_PER_DAY =
  ${simulationMinutesPerDay} as const;

export const CORE_MATERIAL_NAMES: Readonly<Record<number, string>> =
  ${JSON.stringify(materialNames, null, 2)};
`;

fs.writeFileSync(outputPath, output, 'utf8');

